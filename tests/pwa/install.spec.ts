test('deferred installation prompt is consumed once and cancellation is not an error (simulated event)', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Instalar aplicación', exact: true })).toBeVisible()
  await page.evaluate(() => {
    const event = new Event('beforeinstallprompt', { cancelable: true })
    Object.defineProperties(event, {
      prompt: { value: async () => { document.documentElement.dataset.promptCalls = String(Number(document.documentElement.dataset.promptCalls ?? 0) + 1); return { outcome: 'dismissed' } } },
      userChoice: { value: Promise.resolve({ outcome: 'dismissed', platform: 'web' }) },
    })
    window.dispatchEvent(event)
  })
  await page.getByRole('button', { name: 'Instalar aplicación', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Instalación pospuesta' })).toBeVisible()
  expect(await page.locator('html').getAttribute('data-prompt-calls')).toBe('1')
  await page.getByRole('button', { name: 'Instalar aplicación', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.locator('html').getAttribute('data-prompt-calls')).toBe('1')
})

