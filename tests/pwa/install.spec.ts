test('Tabler download explains installation once, then collapses and reopens on hover', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install()
  await page.goto('/')
  const popup = page.getByRole('complementary', { name: 'Instalar GaleoTrack', exact: true })
  const label = popup.locator('.pwa-install-label')
  const icon = popup.locator('.pwa-install-icon')
  await expect(popup.locator('.tabler-icon-download')).toHaveCount(1)
  await expect(icon).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 168, 0)')
  await page.clock.fastForward(800)
  await expect(popup).toHaveAttribute('data-intro', 'expanded')
  await expect(label).toHaveCSS('opacity', '1')
  await expect(icon).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.clock.fastForward(3000)
  await expect(popup).toHaveAttribute('data-intro', 'complete')
  await expect(popup).toHaveAttribute('data-expanded', 'false')
  await expect(label).toHaveCSS('opacity', '0')
  await expect(icon).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 168, 0)')
  await page.screenshot({ path: testInfo.outputPath('download-circle.png') })
  // Only the visible circle can receive a pointer; the clipped capsule must not cover the page.
  const bounds = await popup.boundingBox()
  expect(await page.evaluate(({ x, y }) => Boolean(document.elementFromPoint(x, y)?.closest('.pwa-install')), { x: bounds!.x + 12, y: bounds!.y + 28 })).toBe(false)
  await popup.getByRole('button', { name: 'Instalar aplicación', exact: true }).hover({ position: { x: 196, y: 28 } })
  await expect(popup).toHaveAttribute('data-expanded', 'true')
  await expect(label).toHaveCSS('opacity', '1')
  await expect(popup.getByRole('button', { name: 'Ocultar aviso de instalación', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('download-hover-expanded.png') })
  await page.mouse.move(0, 0)
  await expect(popup).toHaveAttribute('data-expanded', 'false')
  await expect(label).toHaveCSS('opacity', '0')
})

