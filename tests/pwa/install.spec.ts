test('production manifest, brand assets and worker have the expected headers', async ({ request }) => {
  const response = await request.get('/manifest.webmanifest')
  expect(response.status()).toBe(200)
  const manifest = await response.json()
  expect(manifest).toMatchObject({ id: '/', name: 'GaleoTrack', start_url: '/', scope: '/', display: 'standalone', lang: 'es', prefer_related_applications: false })
  for (const icon of manifest.icons) {
    const asset = await request.get(icon.src)
    expect(asset.status()).toBe(200)
    expect(asset.headers()['content-type']).toContain('image/png')
  }
  const sw = await request.get('/sw.js')
  expect(sw.headers()['cache-control']).toContain('no-store')
  expect(sw.headers()['service-worker-allowed']).toBe('/')
  expect(sw.headers()['content-type']).toContain('javascript')
  expect(await sw.text()).not.toContain('__GALEOTRACK_BUILD__')
  const api = await request.get('/api/places?q=rincon')
  expect(api.status()).toBe(401)
  expect(api.headers()['cache-control']).toContain('no-store')
})

test('manual instructions are accessible, responsive, dismissible and return keyboard focus', async ({ page }, testInfo) => {
  await page.addInitScript(() => window.addEventListener('beforeinstallprompt', (event) => event.stopImmediatePropagation(), true))
  await page.goto('/')
  const install = page.getByRole('button', { name: 'Instalar aplicación', exact: true })
  await expect(install).toBeVisible()
  await install.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  expect((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations).toEqual([])
  for (const [width, label] of [[375, 'mobile'], [1440, 'desktop']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await expect(dialog).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`instructions-${label}.png`) })
  }
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(install).toBeFocused()
})

test('installation is one floating bottom action, outside headers, on mobile and desktop', async ({ page }, testInfo) => {
  await page.goto('/')
  const popup = page.getByRole('complementary', { name: 'Instalar GaleoTrack', exact: true })
  await expect(popup).toBeVisible()
  await expect(page.getByRole('banner').getByRole('button', { name: 'Instalar aplicación', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Instalar aplicación', exact: true })).toHaveCount(1)
  for (const width of [320, 375, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(popup).toHaveCSS('position', 'fixed')
    const before = await popup.boundingBox()
    expect(before!.x).toBeGreaterThanOrEqual(16)
    expect(before!.x + before!.width).toBeLessThanOrEqual(width - 15)
    expect(before!.y + before!.height).toBeGreaterThanOrEqual(880)
    expect(before!.y + before!.height).toBeLessThanOrEqual(884)
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
    const after = await popup.boundingBox()
    expect(Math.abs(before!.y - after!.y)).toBeLessThan(1)
    expect((await new AxeBuilder({ page }).include('.pwa-install').analyze()).violations).toEqual([])
    if (width !== 320) await page.screenshot({ path: testInfo.outputPath(`floating-install-${width}.png`) })
    await page.evaluate(() => window.scrollTo(0, 0))
  }
})

