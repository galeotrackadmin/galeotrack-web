test('portada: teclado, texto ampliado, enlaces de registro y rutas protegidas', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 812, height: 375 })
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Ir al contenido principal' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main-content')).toBeFocused()
  await page.addStyleTag({ content: 'html { font-size: 200%; }' })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Acceso estudiante', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/')
  await openSiteMenu(page)
  await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Crear cuenta' }).click()
  await expect(page).toHaveURL(/\/register$/)
  await expect(page.getByLabel('Quiero participar como')).toBeVisible()
})

