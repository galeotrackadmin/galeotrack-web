import AxeBuilder from '@axe-core/playwright'
import { test, expect, openSiteMenu } from './fixtures'

for (const width of [360, 375, 390, 412, 430, 768, 1024, 1366, 1440, 1920]) {
  test(`portada fotográfica accesible y botones de perfiles alineados a ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('tiburones de Puerto Rico')
    const photo = page.locator('.landing-hero-media')
    await expect.poll(() => photo.locator('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
    const photoBounds = await photo.boundingBox()
    const mapBounds = await page.locator('.public-tracker--compact .tracker-canvas').boundingBox()
    expect(Math.abs(photoBounds!.x - mapBounds!.x)).toBeLessThan(1)
    expect(Math.abs(photoBounds!.width - mapBounds!.width)).toBeLessThan(1)
    expect(await photo.evaluate((element) => getComputedStyle(element, '::after').backdropFilter)).toBe('blur(8px)')
    expect(await page.locator('.landing-hero-content').evaluate((element) => getComputedStyle(element).filter)).toBe('none')
    if (width === 375 || width === 1440) await page.screenshot({ path: testInfo.outputPath(`hero-encuadre-${width}.png`), animations: 'disabled', style: 'nextjs-portal { visibility: hidden; }' })
    await expect(page.getByRole('heading', { name: '¿QUÉ ES GALEOTRACK?' })).toBeVisible()
    await expect(page.getByText('una estudiante de bachillerato de Ciencias Marinas', { exact: false })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Pescador Buzo', exact: true })).toBeVisible()
    await expect(page.locator('.landing-principles')).toHaveCount(0)
    await expect(page.getByText('Observar. Conocer. Proteger.', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('contentinfo')).toContainText('© 2026 Galeo Track. Todos los derechos reservados.')
    await expect(page.getByRole('contentinfo')).toContainText('Alexandra Marrero Zambrana')
    await expect(page.getByRole('contentinfo').getByRole('link', { name: 'alexandramarrero68@gmail.com' })).toHaveAttribute('href', 'mailto:alexandramarrero68@gmail.com')
    await expect(page.getByRole('contentinfo').getByRole('link', { name: 'galeotrack.admin@gmail.com' })).toHaveAttribute('href', 'mailto:galeotrack.admin@gmail.com')
    const contact = page.getByRole('contentinfo').locator('#contacto')
    const about = page.getByRole('contentinfo').locator('.site-footer-about')
    await expect(about.locator('.site-footer-founder')).toContainText('Fundadora')
    await expect(about.locator('.site-footer-founder')).toContainText('Alexandra Marrero Zambrana')
    await expect(contact.locator('.site-footer-founder')).toHaveCount(0)
    await expect(contact).not.toContainText('Puerto Rico')
    const cards = page.locator('.landing-role-card')
    await expect(cards).toHaveCount(3)
    for (const card of await cards.all()) {
      await card.scrollIntoViewIfNeeded()
      await expect.poll(() => card.locator('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
      const image = await card.locator('img').boundingBox()
      expect(image?.height).toBeGreaterThan(100)
    }
    const buttons = await page.locator('.landing-role-action').evaluateAll((elements) => elements.map((element) => {
      const rect = element.getBoundingClientRect()
      return { top: rect.top, bottom: rect.bottom, height: rect.height, width: rect.width }
    }))
    expect(buttons.every(({ height, width }) => height >= 44 && width >= 44)).toBe(true)
    if (width >= 1024) {
      expect(Math.max(...buttons.map((b) => b.top)) - Math.min(...buttons.map((b) => b.top))).toBeLessThan(1)
      expect(Math.max(...buttons.map((b) => b.bottom)) - Math.min(...buttons.map((b) => b.bottom))).toBeLessThan(1)
    }
    const science = page.getByRole('article', { name: 'Científico', exact: true })
    const note = await science.locator('.landing-role-note').boundingBox()
    const action = await science.getByRole('link').boundingBox()
    expect(note!.y + note!.height).toBeLessThan(action!.y)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const mapHeight = await page.locator('.public-tracker--compact .tracker-canvas').evaluate((element) => element.getBoundingClientRect().height)
    expect(mapHeight).toBe(width < 768 ? 320 : width < 1200 ? 400 : 480)
    const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).exclude('nextjs-portal').analyze()
    expect(accessibility.violations).toEqual([])
    if (width === 375 || width === 1440) await page.getByRole('contentinfo').screenshot({ path: testInfo.outputPath(`footer-${width}.png`), style: '.site-header, nextjs-portal { visibility: hidden; }' })
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath(`landing-${width}.png`), fullPage: true })
  })
}

test('portada: llenado del botón y escala de perfiles sin desplazar tarjetas vecinas', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const collaborate = page.getByRole('link', { name: 'Cómo colaborar', exact: true })
  const fill = collaborate.locator('.landing-collaborate-fill')
  await expect(page.locator('.landing-hero-actions')).toHaveCSS('transform', 'matrix(1, 0, 0, 1, -48, 0)')
  await expect(fill).toHaveCSS('clip-path', 'inset(0px 100% 0px 0px)')
  await collaborate.hover()
  await expect(fill).toHaveCSS('clip-path', 'inset(0px)')
  await collaborate.screenshot({ path: testInfo.outputPath('colaborar-hover.png') })
  const axe = await new AxeBuilder({ page }).include('.landing-hero').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(axe.violations).toEqual([])
  const cards = page.locator('.landing-role-card')
  await cards.first().scrollIntoViewIfNeeded()
  const neighbor = await cards.nth(1).boundingBox()
  await cards.first().hover()
  await expect(cards.first()).toHaveCSS('transform', 'matrix(1.02, 0, 0, 1.02, 0, 0)')
  expect(await cards.nth(1).boundingBox()).toEqual(neighbor)
  await page.locator('.landing-role-grid').screenshot({ path: testInfo.outputPath('perfiles-hover.png') })
  await page.mouse.move(0, 0)
  await expect(cards.first()).toHaveCSS('transform', 'none')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await cards.first().hover()
  await expect(cards.first()).toHaveCSS('transform', 'none')
  await collaborate.hover()
  await expect(fill).toHaveCSS('transition-property', 'none')
  await collaborate.focus()
  await expect(fill).toHaveCSS('clip-path', 'inset(0px)')
})

